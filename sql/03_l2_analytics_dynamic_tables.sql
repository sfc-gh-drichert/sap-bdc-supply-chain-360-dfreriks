create or replace dynamic table SAP_SUPPLY_CHAIN_DF_V1.ANALYTICS.DT_SUPPLY_CHAIN_GEO(
	FLOW_ID,
	FLOW_TYPE,
	MATERIAL_CATEGORY,
	MONTHLY_VOLUME,
	MONTHLY_VALUE,
	SOURCE_NAME,
	SOURCE_TYPE,
	SOURCE_CITY,
	SOURCE_COUNTRY,
	SOURCE_LAT,
	SOURCE_LON,
	SOURCE_PLANT,
	TARGET_NAME,
	TARGET_TYPE,
	TARGET_CITY,
	TARGET_COUNTRY,
	TARGET_LAT,
	TARGET_LON,
	TARGET_PLANT
) target_lag = 'DOWNSTREAM' refresh_mode = AUTO initialize = ON_CREATE warehouse = LOAD_WH
 as
SELECT
    f.FLOW_ID,
    f.FLOW_TYPE,
    f.MATERIAL_CATEGORY,
    f.MONTHLY_VOLUME,
    f.MONTHLY_VALUE,
    src.NODE_NAME   AS SOURCE_NAME,
    src.NODE_TYPE   AS SOURCE_TYPE,
    src.CITY        AS SOURCE_CITY,
    src.COUNTRY     AS SOURCE_COUNTRY,
    src.LATITUDE    AS SOURCE_LAT,
    src.LONGITUDE   AS SOURCE_LON,
    src.PLANT       AS SOURCE_PLANT,
    tgt.NODE_NAME   AS TARGET_NAME,
    tgt.NODE_TYPE   AS TARGET_TYPE,
    tgt.CITY        AS TARGET_CITY,
    tgt.COUNTRY     AS TARGET_COUNTRY,
    tgt.LATITUDE    AS TARGET_LAT,
    tgt.LONGITUDE   AS TARGET_LON,
    tgt.PLANT       AS TARGET_PLANT
FROM SAP_SUPPLY_CHAIN_DF_V1.MANUFACTURING_CODES.A_SUPPLY_CHAIN_FLOWS f
JOIN SAP_SUPPLY_CHAIN_DF_V1.MANUFACTURING_CODES.A_SUPPLY_CHAIN_NODES src ON f.SOURCE_NODE = src.NODE_ID
JOIN SAP_SUPPLY_CHAIN_DF_V1.MANUFACTURING_CODES.A_SUPPLY_CHAIN_NODES tgt ON f.TARGET_NODE = tgt.NODE_ID;
create or replace dynamic table SAP_SUPPLY_CHAIN_DF_V1.ANALYTICS.DT_WORK_CENTER_UTILIZATION(
	WORK_CENTER,
	WORK_CENTER_DESC,
	PLANT,
	PLANT_NAME,
	AVAILABLE_CAPACITY_HRS,
	USED_CAPACITY_HRS,
	UTILIZATION_PCT,
	PERIOD_DATE
) target_lag = 'DOWNSTREAM' refresh_mode = AUTO initialize = ON_CREATE warehouse = LOAD_WH
 as
SELECT
    wc.WORK_CENTER,
    w.WORK_CENTER_DESC,
    wc.PLANT,
    p.PLANT_NAME,
    wc.AVAILABLE_CAPACITY_HRS,
    wc.USED_CAPACITY_HRS,
    ROUND(100.0 * wc.USED_CAPACITY_HRS / NULLIF(wc.AVAILABLE_CAPACITY_HRS, 0), 1) AS UTILIZATION_PCT,
    wc.PERIOD_DATE
FROM SAP_SUPPLY_CHAIN_DF_V1.WORK_CENTER.A_WORK_CENTER_CAPACITY wc
JOIN SAP_SUPPLY_CHAIN_DF_V1.WORK_CENTER.A_WORK_CENTER w ON wc.WORK_CENTER = w.WORK_CENTER AND wc.PLANT = w.PLANT
JOIN SAP_SUPPLY_CHAIN_DF_V1.PLANT.A_PLANT p ON wc.PLANT = p.PLANT;

