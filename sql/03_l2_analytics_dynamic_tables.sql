-- =====================================================================
-- L2 (gold) — Analytics dynamic tables
-- Joined / enriched / aggregated analytics objects built on the raw L0
-- SAP BDC standard data products. Dynamic tables auto-refresh
-- (TARGET_LAG). Requires a warehouse named LOAD_WH (or edit WAREHOUSE).
-- =====================================================================

create or replace schema SAP_SUPPLY_CHAIN_DF_V1.ANALYTICS COMMENT='L2: Dynamic tables - analytics-ready joined/enriched data';

create or replace dynamic table SAP_SUPPLY_CHAIN_DF_V1.ANALYTICS.DT_BOM_EXPLOSION(
	PARENT_MATERIAL,
	PARENT_DESC,
	BOM_NUMBER,
	BOM_LEVEL,
	COMPONENT_MATERIAL,
	COMPONENT_DESC,
	COMPONENT_QTY,
	COMPONENT_UOM,
	BASE_QTY,
	ITEM_CATEGORY,
	COMPONENT_COST
) target_lag = 'DOWNSTREAM' refresh_mode = AUTO initialize = ON_CREATE warehouse = LOAD_WH
 as
SELECT
    b.PARENT_MATERIAL,
    b.PARENT_DESC,
    b.BOM_NUMBER,
    b.BOM_LEVEL,
    b.COMPONENT_MATERIAL,
    b.COMPONENT_DESC,
    b.COMPONENT_QTY,
    b.COMPONENT_UOM,
    b.BASE_QTY,
    b.ITEM_CATEGORY,
    b.COMPONENT_COST
FROM SAP_SUPPLY_CHAIN_DF_V1.BILL_OF_MATERIAL.A_BOM_ITEM b;
create or replace dynamic table SAP_SUPPLY_CHAIN_DF_V1.ANALYTICS.DT_DELIVERY_PERFORMANCE(
	DELIVERY_ID,
	SHIPPING_POINT,
	SHIPPING_POINT_DESC,
	MATERIAL,
	MATERIAL_DESC,
	DELIVERY_QTY,
	PLANNED_DELIVERY_DATE,
	ACTUAL_DELIVERY_DATE,
	ON_TIME_FLAG,
	DELAY_DAYS,
	DELIVERY_MONTH
) target_lag = 'DOWNSTREAM' refresh_mode = AUTO initialize = ON_CREATE warehouse = LOAD_WH
 as
SELECT
    d.DELIVERY_ID,
    d.SHIPPING_POINT,
    sp.SHIPPING_POINT_DESC,
    d.MATERIAL,
    d.MATERIAL_DESC,
    d.DELIVERY_QTY,
    d.PLANNED_DELIVERY_DATE,
    d.ACTUAL_DELIVERY_DATE,
    d.ON_TIME_FLAG,
    d.DELAY_DAYS,
    d.DELIVERY_MONTH
FROM SAP_SUPPLY_CHAIN_DF_V1.DELIVERY_MGMT_CONFIG.A_DELIVERY d
JOIN SAP_SUPPLY_CHAIN_DF_V1.SHIPPING_POINT.A_SHIPPING_POINT sp ON d.SHIPPING_POINT = sp.SHIPPING_POINT;
create or replace dynamic table SAP_SUPPLY_CHAIN_DF_V1.ANALYTICS.DT_INVENTORY_OVERVIEW(
	MATERIAL,
	MATERIAL_DESC,
